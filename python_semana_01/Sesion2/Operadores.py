# Leer dos numeros y mostrar la suma, resta, multiplicacion, division, modulo

num1 = int(input("Ingresa un #: "))
num2 = int(input("Ingresa otro #: "))

suma = num1 + num2
resta = num1 - num2
multiplicacion = num1 * num2
division = num1 / num2
divisible = num1 % num2

print(f"Suma: {suma}")
print(f"Resta: {resta}")
print(f"Multiplicación: {multiplicacion}")
print(f"División: {division}")
print(f"Divisible: {divisible}")