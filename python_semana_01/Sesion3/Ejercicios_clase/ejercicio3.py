# Lee una cantidad de horas y calcula cuántos minutos y segundos representa.

Horas =int(input("Ingrese la cantidad de horas que quiere convertir en minutos y segundos: "))

Minutos = Horas * 60
Segundos = Horas * 3600

print(f"{Horas} horas equivalen a {Minutos} minutos y {Segundos} segundos.")